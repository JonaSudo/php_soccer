"""Build ball.urdf and ball.xml from ball.yaml.

The ball is a single free body with a sphere collision. Holosoma spawns it as
the rigid object ``ball`` (IsaacSim reads the URDF, MuJoCo the MJCF). Never
edit the generated files; change ``ball.yaml`` and rerun this script.
"""

from __future__ import annotations

from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent


def load_spec(path: Path = HERE / "ball.yaml") -> dict:
    raw = yaml.safe_load(path.read_text())
    spec = {k: (v["value"] if isinstance(v, dict) else v) for k, v in raw.items()}
    spec["radius"] = spec["diameter"] / 2.0
    factor = 2.0 / 3.0 if spec.get("shell_inertia", True) else 2.0 / 5.0
    spec["inertia"] = factor * spec["mass"] * spec["radius"] ** 2
    return spec


def urdf_text(spec: dict) -> str:
    r, m, i = spec["radius"], spec["mass"], spec["inertia"]
    return f"""<?xml version="1.0" ?>
<!-- generated by robots/ball/build_ball.py from ball.yaml, do not edit -->
<robot name="ball">
  <link name="ball">
    <inertial>
      <origin xyz="0 0 0"/>
      <mass value="{m:.6g}"/>
      <inertia ixx="{i:.6g}" ixy="0" ixz="0" iyy="{i:.6g}" iyz="0" izz="{i:.6g}"/>
    </inertial>
    <contact>
      <lateral_friction value="{spec['friction']:.6g}"/>
      <restitution value="{spec['restitution']:.6g}"/>
    </contact>
    <visual>
      <geometry><sphere radius="{r:.6g}"/></geometry>
      <material name="ball_white"><color rgba="0.95 0.95 0.95 1"/></material>
    </visual>
    <collision>
      <geometry><sphere radius="{r:.6g}"/></geometry>
    </collision>
  </link>
</robot>
"""


def mjcf_text(spec: dict) -> str:
    r, m, i = spec["radius"], spec["mass"], spec["inertia"]
    # One top-level body without joint: holosoma adds the free joint.
    return f"""<!-- generated by robots/ball/build_ball.py from ball.yaml, do not edit -->
<mujoco model="ball">
  <worldbody>
    <body name="ball">
      <inertial pos="0 0 0" mass="{m:.6g}" diaginertia="{i:.6g} {i:.6g} {i:.6g}"/>
      <geom name="ball" type="sphere" size="{r:.6g}" friction="{spec['friction']:.6g} 0.005 0.0001" rgba="0.95 0.95 0.95 1"/>
    </body>
  </worldbody>
</mujoco>
"""


def main() -> None:
    spec = load_spec()
    (HERE / "ball.urdf").write_text(urdf_text(spec))
    (HERE / "ball.xml").write_text(mjcf_text(spec))
    print(f"ball: d={spec['diameter']} m, m={spec['mass']} kg, I={spec['inertia']:.3e} kg*m^2")


if __name__ == "__main__":
    main()
